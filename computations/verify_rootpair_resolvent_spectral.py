#!/usr/bin/env python3
"""Exact checks for root-pair resolvent and torsion-free spectral avatar.

Supports:
  thm:qa-noncubic-rootpair-quartic-resolvent
  thm:qa-noncubic-rootpair-torsionfree-spectral-module
  prop:qa-rootpair-nodal-picard-nonextension

Run: python3 computations/verify_rootpair_resolvent_spectral.py
Standard library only. The module's geometric torsion-freeness,
reflexivity, descent and Picard nonextension are mathematical proofs
in the manuscript, NOT asserted to be formally verified by this script.
"""
from itertools import combinations
from math import prod


def elementary(roots, i):
    return sum(prod(combination) for combination in combinations(roots, i))


def quartic_resolvent(roots):
    assert len(roots) == 4
    a, b, c, d = (-elementary(roots, 1), elementary(roots, 2),
                  -elementary(roots, 3), elementary(roots, 4))
    expected = (1, -b, a*c - 4*d, -(a*a*d + c*c - 4*b*d))
    w, x, y, z = roots
    resolvent_roots = (w*x + y*z, w*y + x*z, w*z + x*y)
    actual = (1, -sum(resolvent_roots),
              elementary(resolvent_roots, 2),
              -prod(resolvent_roots))
    assert expected == actual
    return resolvent_roots


def coefficient_roots():
    assert set(quartic_resolvent((0, 1, 2, 3))) == {2, 3, 6}
    assert sorted(quartic_resolvent((0, 0, 1, 2))) == [0, 0, 2]
    assert sorted(quartic_resolvent((0, 0, 1, 1))) == [0, 0, 1]
    for roots in ((1, 3, 5, 7), (1, 2, 3, 4), (-3, -1, 2, 6),
                  (0, 2, 4, 9), (-3, -3, 1, 5), (1, 1, 4, 4)):
        quartic_resolvent(roots)
    print("PASS: cubic resolvent coefficients, smooth/nodal/I2 sample multiplicities")


# Z[x,s] polynomials are dictionaries (x_degree,s_degree)->integer.
def poly(terms):
    return {k: v for k, v in terms.items() if v}


def mul(u, v):
    out = {}
    for (i, j), a in u.items():
        for (k, l), b in v.items():
            key = (i+k, j+l)
            out[key] = out.get(key, 0) + a*b
    return poly(out)


def add(u, v):
    out = dict(u)
    for k, val in v.items():
        out[k] = out.get(k, 0) + val
    return poly(out)


def neg(u):
    return {k: -a for k, a in u.items()}


def matrix_factorization():
    # f1=x(x-1), f2=(x-s)(x-2)
    f1 = {(2, 0): 1, (1, 0): -1}
    f2 = {(2, 0): 1, (1, 1): -1, (1, 0): -2, (0, 1): 2}
    q = mul(f1, f2)
    A = [[{}, f2], [f1, {}]]
    AA = [[add(mul(A[i][0], A[0][j]), mul(A[i][1], A[1][j]))
           for j in range(2)] for i in range(2)]
    assert AA == [[q, {}], [{}, q]]
    # When s=0, q=x^2(x-1)(x-2), with one double root.
    q0 = {(i, j): a for (i, j), a in q.items() if j == 0}
    assert q0 == {(4, 0): 1, (3, 0): -3, (2, 0): 2}
    # At f1=f2=x(x-1), q=x^2(x-1)^2: two double roots.
    equal = mul(f1, f1)
    assert equal == {(4, 0): 1, (3, 0): -2, (2, 0): 1}
    print("PASS: universal 2x2 matrix factorization A^2=f1*f2*I")
    print("PASS: shared-root and equal-pair singular quartic specializations")


def invariant_parity():
    # k[c,d]^(c,d)->(-c,-d) is generated by x=c^2,v=d^2,y=cd,
    # subject to y^2=xv; anti-invariant part by c,d.
    for i in range(13):
        for j in range(13):
            if (i+j) % 2 == 0:
                if i%2 == 0:
                    assert j%2 == 0
                    assert (2*(i//2), 2*(j//2)) == (i, j)
                else:
                    assert j%2 == 1
                    assert (2*((i-1)//2)+1, 2*((j-1)//2)+1) == (i, j)
            elif i%2:
                assert not j%2
                assert (2*((i-1)//2)+1, 2*(j//2)) == (i, j)
            else:
                assert j%2
                assert (2*(i//2), 2*((j-1)//2)+1) == (i, j)
    # The relation y^2=x(x-s) follows from
    # x=c^2, x-s=d^2, y=cd.
    assert (2, 2) == (1+1, 1+1)
    # Odd part has two minimal degree-one generators c,d.
    assert len([x for x in ((1, 0), (0, 1)) if sum(x)==1]) == 2
    print("PASS: A1 quotient even generators x,v,y and odd c,d through degree 24")
    print("PASS: odd module has two generators at the A1 vertex; cannot be rank-one free")


if __name__ == "__main__":
    coefficient_roots()
    matrix_factorization()
    invariant_parity()
