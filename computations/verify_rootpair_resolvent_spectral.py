from itertools import combinations
from math import prod


def elementary(roots, i):
    return sum(prod(combination) for combination in combinations(roots, i))


def quartic_resolvent(roots):
    assert len(roots) == 4
    a, b, c, d = (-elementary(roots, 1), elementary(roots, 2),
                  -elementary(roots, 3), elementary(roots, 4))
    expected = (1, -b, a*c - 4*d, -(a*a*d + c*c - 4*b*d))
    w, x, y, z = roots
    resolvent_roots = (w*x + y*z, w*y + x*z, w*z + x*y)
    actual = (1, -sum(resolvent_roots),
              elementary(resolvent_roots, 2),
              -prod(resolvent_roots))
    assert expected == actual
    return resolvent_roots


def coefficient_roots():
    assert set(quartic_resolvent((0, 1, 2, 3))) == {2, 3, 6}
    assert sorted(quartic_resolvent((0, 0, 1, 2))) == [0, 0, 2]
    assert sorted(quartic_resolvent((0, 0, 1, 1))) == [0, 0, 1]
    for roots in ((1, 3, 5, 7), (1, 2, 3, 4), (-3, -1, 2, 6),
                  (0, 2, 4, 9), (-3, -3, 1, 5), (1, 1, 4, 4)):
        quartic_resolvent(roots)
    print("PASS: cubic resolvent coefficients, smooth/nodal/I2 sample multiplicities")


# Z[x,s] polynomials are dictionaries (x_degree,s_degree)->integer.
def poly(terms):
    return {k: v for k, v in terms.items() if v}


def mul(u, v):
    out = {}
    for (i, j), a in u.items():
        for (k, l), b in v.items():
            key = (i+k, j+l)
            out[key] = out.get(key, 0) + a*b
    return poly(out)


def add(u, v):
    out = dict(u)
    for k, val in v.items():
        out[k] = out.get(k, 0) + val
    return poly(out)


def neg(u):
    return {k: -a for k, a in u.items()}


def matrix_factorization():
    # f1=x(x-1), f2=(x-s)(x-2)
    f1 = {(2, 0): 1, (1, 0): -1}
    f2 = {(2, 0): 1, (1, 1): -1, (1, 0): -2, (0, 1): 2}
    q = mul(f1, f2)
    A = [[{}, f2], [f1, {}]]
    AA = [[add(mul(A[i][0], A[0][j]), mul(A[i][1], A[1][j]))
           for j in range(2)] for i in range(2)]
    assert AA == [[q, {}], [{}, q]]
    # When s=0, q=x^2(x-1)(x-2), with one double root.
    q0 = {(i, j): a for (i, j), a in q.items() if j == 0}
    assert q0 == {(4, 0): 1, (3, 0): -3, (2, 0): 2}
    # At f1=f2=x(x-1), q=x^2(x-1)^2: two double roots.
    equal = mul(f1, f1)
    assert equal == {(4, 0): 1, (3, 0): -2, (2, 0): 1}
    print("PASS: universal 2x2 matrix factorization A^2=f1*f2*I")
    print("PASS: shared-root and equal-pair singular quartic specializations")


def invariant_parity():
    # k[c,d]^(c,d)->(-c,-d) is generated by x=c^2,v=d^2,y=cd,
    # subject to y^2=xv; anti-invariant part by c,d.
    for i in range(13):
        for j in range(13):
            if (i+j) % 2 == 0:
                if i%2 == 0:
                    assert j%2 == 0
                    assert (2*(i//2), 2*(j//2)) == (i, j)
                else:
                    assert j%2 == 1
                    assert (2*((i-1)//2)+1, 2*((j-1)//2)+1) == (i, j)
            elif i%2:
                assert not j%2
                assert (2*((i-1)//2)+1, 2*(j//2)) == (i, j)
            else:
                assert j%2
                assert (2*(i//2), 2*((j-1)//2)+1) == (i, j)
    # The relation y^2=x(x-s) follows from
    # x=c^2, x-s=d^2, y=cd.
    assert (2, 2) == (1+1, 1+1)
    # Odd part has two minimal degree-one generators c,d.
    assert len([x for x in ((1, 0), (0, 1)) if sum(x)==1]) == 2
    print("PASS: A1 quotient even generators x,v,y and odd c,d through degree 24")
    print("PASS: odd module has two generators at the A1 vertex; cannot be rank-one free")



def singular_square_avatar_models():
    from fractions import Fraction
    # Nodal curve: normalization t -> (X=t^2, Z=(1-t^2)/t)
    for t in (Fraction(-3), Fraction(-2), Fraction(-1), Fraction(1),
              Fraction(2), Fraction(3)):
        X = t*t
        Z = (1-X)/t
        assert X*Z*Z == (1-X)*(1-X)
    # The two preimages t=1 and t=-1 of the node map to (1,0).
    assert (Fraction(1)**2, (1-1)/Fraction(1)) == (1,0)
    assert (Fraction(-1)**2, (1-1)/Fraction(-1)) == (1,0)
    # Tangent vectors on the two branches at the node are
    # (dX/dt,dZ/dt)=(2,-2) and (-2,-2), with nonzero determinant.
    assert 2*(-2)-(-2)*(-2) == -8
    # I2 curve: the union Z=X and Z=-X. The factors meet at 0
    # and infinity and are distinct in characteristic zero.
    for X in (0, 1, -1, 2, 3, 5):
        for Z in (X, -X):
            assert (Z-X)*(Z+X) == 0
    assert 1 != -1
    print("PASS: nodal square avatar equation X*Z^2=(1-X)^2")
    print("PASS: two-branch node transverse tangent determinant")
    print("PASS: I2 square avatar is two distinct (1,1) graphs")



def verify_point_curve_two_isogeny_j():
    """Exact quartic invariant witness: E_f and C_q are 2-isogenous, not isomorphic.

    The birational parameter t=d/(x-3) for
    c²=x(x-1), d²=(x-2)(x-3) gives
       z²=6*t**4-7*t**2+2,
    whereas C_q is y²=x*(x-1)*(x-2)*(x-3).
    This script tests the two quartic j invariants, not an elliptic
    curve isogeny certificate or the global geometric construction.
    """
    from fractions import Fraction

    def j_quartic(a, b, c, d, e):
        I = 12*a*e - 3*b*d + c*c
        J = 72*a*c*e + 9*b*c*d - 27*a*d*d - 27*b*b*e - 2*c*c*c
        delta = 4*I**3-J**2
        assert delta
        return Fraction(1728*4*I**3, delta)

    # Expand x(x-1)(x-2)(x-3) = x^4 - 6x^3 + 11x^2 - 6x.
    j_spectral = j_quartic(1, -6, 11, -6, 0)
    # Under t=d/(x-3), z=(t²-1)c:
    # z²=(3t²-2)(2t²-1)=6t^4-7t²+2.
    j_point = j_quartic(6, 0, -7, 0, 2)
    assert j_spectral == Fraction(35152, 9)
    assert j_point == Fraction(28756228, 3)
    assert j_point != j_spectral
    # Classical modular polynomial Phi_2(X,Y), checked exactly at both j's.
    X, Y = j_point, j_spectral
    phi2 = (X**3 + Y**3 - X**2*Y**2
            + 1488*X*Y*(X+Y) - 162000*(X**2+Y**2)
            + 40773375*X*Y + 8748000000*(X+Y)
            - 157464000000000)
    assert phi2 == 0
    print("PASS: point and spectral curves have distinct j and satisfy Phi_2(jE,jC)=0")


